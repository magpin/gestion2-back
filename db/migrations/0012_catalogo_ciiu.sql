-- 0012_catalogo_ciiu — CIIU Rev. 4 A.C. (DANE) adoptada por la DIAN
-- =============================================================================
-- Catálogo NORMATIVO externo: sin empresa_id, sin RLS, solo lectura para la API.
--
-- Versión: Resolución DIAN 000114 de 2020 (vigente desde 2021). Frente a la
-- Rev. 4 A.C. de 2012 esta incorpora: 6496 Capitalización (reubicada del grupo
-- 651 al 649), 6515 y 6523 nuevas, 7110 dividida en 7111/7112, y 8890 dividida
-- en 8891/8899. Un contribuyente con actividad 7112 no existe en la de 2012.
--
-- 4 niveles y la jerarquía se deriva del propio código: sección (letra) >
-- división (2) > grupo (3) > clase (4). La CLASE es la que va en el RUT
-- (casillas 46/48/50) y la que referencia empresa_actividad_economica.
--
-- ciiu_clase.origen distingue 'DANE' (CIIU real) de 'DIAN' (clasificaciones
-- para personas naturales que no tienen grupo CIIU: asalariados, pensionados,
-- rentistas). Sin esas 5 filas no se puede registrar un asalariado.

CREATE TABLE ciiu_seccion (
  codigo  char(1) PRIMARY KEY CHECK (codigo ~ '^[A-U]$'),
  nombre  text    NOT NULL
);

CREATE TABLE ciiu_division (
  codigo          char(2) PRIMARY KEY CHECK (codigo ~ '^[0-9]{2}$'),
  seccion_codigo  char(1) NOT NULL REFERENCES ciiu_seccion (codigo),
  nombre          text    NOT NULL
);

CREATE TABLE ciiu_grupo (
  codigo           char(3) PRIMARY KEY CHECK (codigo ~ '^[0-9]{3}$'),
  division_codigo  char(2) NOT NULL REFERENCES ciiu_division (codigo),
  nombre           text    NOT NULL,

  -- La jerarquía vive en el código. Esto impide que un grupo cuelgue de una
  -- división que no es su prefijo.
  CONSTRAINT ck_ciiu_grupo_prefijo CHECK (left(codigo, 2) = division_codigo)
);

CREATE TABLE ciiu_clase (
  codigo        char(4) PRIMARY KEY CHECK (codigo ~ '^[0-9]{4}$'),
  grupo_codigo  char(3) REFERENCES ciiu_grupo (codigo),
  nombre        text    NOT NULL,
  origen        text    NOT NULL DEFAULT 'DANE' CHECK (origen IN ('DANE', 'DIAN')),

  -- Las clases DANE cuelgan siempre de su grupo; las DIAN nunca tienen grupo.
  CONSTRAINT ck_ciiu_clase_grupo CHECK (
    (origen = 'DANE' AND grupo_codigo IS NOT NULL AND left(codigo, 3) = grupo_codigo)
    OR
    (origen = 'DIAN' AND grupo_codigo IS NULL)
  )
);

CREATE INDEX ix_ciiu_division_seccion ON ciiu_division (seccion_codigo);
CREATE INDEX ix_ciiu_grupo_division   ON ciiu_grupo (division_codigo);
CREATE INDEX ix_ciiu_clase_grupo      ON ciiu_clase (grupo_codigo);
CREATE INDEX ix_ciiu_clase_busqueda   ON ciiu_clase (fn_normalizar(nombre));

COMMENT ON TABLE  ciiu_clase IS
  'CIIU Rev. 4 A.C. nivel clase (4 digitos). Es el codigo que va en el RUT. Fuente: DANE / Resolucion DIAN 000114 de 2020.';
COMMENT ON COLUMN ciiu_clase.origen IS
  'DIAN = clasificacion propia de la DIAN para personas naturales sin actividad CIIU (asalariado, pensionado, rentista).';

