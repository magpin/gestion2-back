-- =============================================================================
-- 0015_catalogo_puc — Plan Único de Cuentas, Decreto 2650 de 1993
-- =============================================================================
-- Catálogo NORMATIVO: sin empresa_id, sin RLS, solo lectura para la API. Llega
-- hasta la subcuenta de 6 dígitos, que es donde termina el decreto. De ahí para
-- abajo (auxiliares de 7 dígitos o más) cada empresa arma lo suyo en
-- empresa_cuenta — ver 0016.
--
-- CUATRO NIVELES, y la longitud del código ES el nivel:
--   1 dígito  clase      1 ACTIVO
--   2 dígitos grupo      11 DISPONIBLE
--   4 dígitos cuenta     1105 CAJA
--   6 dígitos subcuenta  110505 CAJA GENERAL   <- la única imputable
--
-- NATURALEZA: se calculó, no se copió. La base es la clase (1,5,6,7,8 débito;
-- 2,3,4,9 crédito) y encima pesan las cuentas de naturaleza contraria, que el
-- decreto marca "(DB)" o "(CR)" dentro del propio nombre — por eso las marcas se
-- conservan en el texto y no se limpiaron. Las once cuentas acumuladas del activo
-- (1592 depreciación, 1597/1698/1798 amortización, 1598 agotamiento, 1299/1399/
-- 1499/1599/1699/1899 provisiones) llegaron sin marca en el origen y van forzadas
-- a crédito explícitamente.
--
-- PROCEDENCIA DE LOS DATOS: extraídos de una base Access en producción de una
-- empresa (../docs/bddCaja). Esa base tenía el catálogo mezclado con las cuentas
-- propias de la empresa, así que el nivel 6 se filtró:
--   2084 subcuentas del decreto -> entran acá
--   18 códigos que había elegido la empresa -> van a empresa_cuenta
--   36 filas "(rango N a M)" del sistema anterior -> se descartan, no son cuentas
-- El detalle de lo excluido está en ../docs/puc_exclusiones.md.
--
-- RANGO LIBRE: el decreto no numera todo. En 111 nodos dice explícitamente
-- "7101 a 7199" o "220501 a 220598" y deja que cada empresa numere sus hijas.
-- Toda la clase 7 (costos de producción) y las cuentas de orden por contra
-- (82, 84, 85, 86, 92, 94, 95, 96) son así: por eso llegan sin cuentas de 4
-- dígitos y NO es que falten. La columna rango_libre marca esos nodos para que
-- la aplicación distinga "acá numerás vos" de "esto está incompleto".
-- Cotejado contra el texto del Decreto 2650 (dos ediciones distintas del PDF).

CREATE TABLE cuenta_puc (
  codigo        varchar(6) PRIMARY KEY CHECK (codigo ~ '^[0-9]{1,6}$'),
  nivel         smallint   NOT NULL CHECK (nivel IN (1, 2, 4, 6)),
  codigo_padre  varchar(6) REFERENCES cuenta_puc (codigo),
  nombre        text       NOT NULL,
  naturaleza    text       NOT NULL CHECK (naturaleza IN ('DEBITO', 'CREDITO')),
  -- Solo la subcuenta recibe movimiento. Los tres niveles de arriba suman a sus
  -- hijas y no se asientan nunca.
  es_imputable  boolean    NOT NULL,
  -- El decreto deja sin numerar las hijas de este nodo: las inventa la empresa,
  -- dentro del rango que el propio decreto indica. Un nodo con rango_libre y sin
  -- hijas está completo, no incompleto.
  rango_libre   boolean    NOT NULL DEFAULT false,

  -- El nivel no se declara aparte del código: es su longitud.
  CONSTRAINT ck_puc_nivel_longitud CHECK (length(codigo) = nivel),
  -- La jerarquía vive en el código. Una subcuenta no puede colgar de otra cuenta.
  CONSTRAINT ck_puc_padre_prefijo CHECK (
    (nivel = 1 AND codigo_padre IS NULL)
    OR
    (nivel > 1 AND codigo_padre IS NOT NULL AND left(codigo, length(codigo_padre)) = codigo_padre)
  ),
  CONSTRAINT ck_puc_imputable CHECK (es_imputable = (nivel = 6))
);

CREATE INDEX ix_puc_padre    ON cuenta_puc (codigo_padre);
CREATE INDEX ix_puc_nivel    ON cuenta_puc (nivel);
CREATE INDEX ix_puc_busqueda ON cuenta_puc (fn_normalizar(nombre));
CREATE INDEX ix_puc_rango_libre ON cuenta_puc (codigo) WHERE rango_libre;

COMMENT ON TABLE  cuenta_puc IS
  'PUC Decreto 2650 de 1993. Catalogo normativo compartido: ninguna empresa lo edita.';
COMMENT ON COLUMN cuenta_puc.naturaleza IS
  'Naturaleza calculada desde la clase, con las cuentas de naturaleza contraria del decreto (marcadas (DB)/(CR) en el nombre) ya aplicadas.';
COMMENT ON COLUMN cuenta_puc.es_imputable IS
  'true solo en nivel 6. Es la unica cuenta del catalogo que puede recibir un asiento.';
COMMENT ON COLUMN cuenta_puc.rango_libre IS
  'El decreto no numera las hijas de este nodo: las define cada empresa (ej. 7101 a 7199, 220501 a 220598). Sin hijas y con rango_libre = completo, no incompleto.';

